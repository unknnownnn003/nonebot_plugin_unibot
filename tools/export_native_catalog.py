def literal(node, bindings):
    if isinstance(node, ast.Name) and node.id in bindings:
        return literal(bindings[node.id], bindings)
    if isinstance(node, ast.Attribute) and node.attr == "pattern":
        return literal(node.value, bindings)
    if isinstance(node, ast.Call) and ast.unparse(node.func) == "re.compile":
        return literal(node.args[0], bindings)
    return ast.literal_eval(node)


def registrations(root):
    output = {}
    for path in sorted(root.glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
        bindings = {n.targets[0].id: n.value for n in tree.body if isinstance(n, ast.Assign)
                    and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name)}
        for name, node in bindings.items():
            if not isinstance(node, ast.Call) or not ast.unparse(node.func).startswith("on_"):
                continue
            kind = ast.unparse(node.func)
            entry = dict(module=path.stem, matcher=name, registration=kind, line=node.lineno)
            target = node.args[0] if node.args else next((k.value for k in node.keywords if k.arg == "pattern"), None)
            if target is not None:
                entry["pattern" if kind == "on_regex" else "command"] = literal(target, bindings)
            for keyword in node.keywords:
                if keyword.arg == "aliases":
                    entry["aliases"] = sorted(literal(keyword.value, bindings))
                elif keyword.arg in {"permission", "rule"}:
                    # Source expression, not a claim that the caller is authorized.
                    entry[keyword.arg + "_source"] = ast.unparse(keyword.value)
            output[f"{path.stem}.{name}"] = entry
    return output


def export(root, mapping):
    entries = registrations(root)
    caps = {}
    for capability, refs in mapping.items():
        caps[capability] = {
            "native_commands": [dict(entries[ref], **({"condition": CONDITIONS[capability, ref]}
                if (capability, ref) in CONDITIONS else {})) for ref in refs.split()],
            "native_command_note": "原注册入口；参数语法和运行时命令前缀以原插件为准。" if refs else
                "此能力没有对应的独立原生命令；不将相关命令或旧绘图入口冒充为等价命令。",
        }
    source = '"""Generated by tools/export_native_catalog.py; do not edit."""\nimport json\n\nNATIVE_CATALOG = json.loads(r\'\'\'' + json.dumps(caps, ensure_ascii=False, indent=2, sort_keys=True) + "''' )\n"

    return source + "\n# OAuth stays native-only and never enters the model tool catalog.\nNATIVE_ONLY_COMMANDS = json.loads(r\'\'\'" + json.dumps([entries[ref] for ref in NATIVE_ONLY.split()], ensure_ascii=False, indent=2, sort_keys=True) + "\'\'\' )\n"


def declared_capabilities(root):
    tree = ast.parse((root / "llm_api.py").read_text(encoding="utf-8-sig"))
    definitions = next((n.value for n in tree.body if isinstance(n, ast.Assign)
                        and any(isinstance(t, ast.Name) and t.id == "_DEFINITIONS" for t in n.targets)), None)
    if definitions is not None:
        return {ast.literal_eval(row.elts[0]) for row in definitions.elts}
    describe = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "_describe_capabilities")
    return {ast.literal_eval(k.value) for n in ast.walk(describe) if isinstance(n, ast.Call)
            and isinstance(n.func, ast.Name) and n.func.id == "dict" for k in n.keywords if k.arg == "id"}



def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if set(UNI) != declared_capabilities(ROOT):
        raise ValueError("UniBot capability mapping differs from llm_api")
    source = export(ROOT, UNI)
    target = ROOT / "services/native_catalog.py"
    if args.check:
        if target.read_text(encoding="utf-8") != source:
            raise SystemExit("Stale UniBot native catalog")
    else:
        target.write_text(source, encoding="utf-8")
    print(f"UniBot: {len(UNI)} capabilities checked")


if __name__ == "__main__":
    main()
